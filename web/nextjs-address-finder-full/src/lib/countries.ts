const BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]))

/** Look a country up by alpha-2 code, case-insensitively. */
export function countryInfo(
  code: string | null | undefined,
): CountryInfo | undefined {
  return code ? BY_CODE.get(code.trim().toUpperCase()) : undefined
}

/** Centre of a bbox — where a query should be biased when nothing better is known. */
export function bboxCenter(
  bbox: [number, number, number, number],
): [number, number] {
  return [(bbox[0] + bbox[2]) / 2, (bbox[1] + bbox[3]) / 2]
}
